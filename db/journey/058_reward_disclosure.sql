-- ===========================================================================
-- MEBODY — 적립 고지 문구 보강
--
-- ※ db/journey 폴더의 058 입니다. 057 을 이미 적용한 뒤에 돌리면 됩니다.
--
-- 057 을 적용한 다음에 고지에서 빠진 것을 찾았습니다.
--   · 확률을 "고르게" 라고만 썼는데, 얼마인지(1/6)를 적어야 고지입니다
--   · 하루 1회라는 것과 다음 굴리기가 언제 열리는지(오전 5시)가 없었습니다
--
-- 금액이나 규칙은 바꾸지 않습니다. 말만 정확해집니다.
-- ===========================================================================

UPDATE public.reward_rules SET
  disclosure = '주사위 눈은 1~6이 각각 1/6 확률로 고르게 나옵니다. 5눈은 1원, 6눈은 2원이고 나머지 눈은 적립이 없습니다. 하루 1회이며 다음 굴리기는 오전 5시에 열립니다. 무료 적립은 한 달 49원을 넘지 않습니다.',
  updated_at = now()
WHERE code = 'daily_routine_dice';

UPDATE public.reward_rules SET
  disclosure = '주사위 눈은 1~6이 각각 1/6 확률로 고르게 나옵니다. 6눈일 때만 1원이 적립됩니다. 하루 1회이며 다음 굴리기는 오전 5시에 열립니다. 무료 적립은 한 달 49원을 넘지 않습니다.',
  updated_at = now()
WHERE code = 'routine_bonus_dice';

UPDATE public.reward_rules SET
  disclosure = '미션을 마치면 확률에 따라 적립됩니다. 100번 중 22번은 1원, 3번은 2원이고 나머지 75번은 적립이 없습니다. 무료 적립은 한 달 49원을 넘지 않습니다.',
  updated_at = now()
WHERE code = 'daily_mission';

-- ---------------------------------------------------------------------------
-- 확인 — 표시 최대치가 실제로 받을 수 있는 금액과 같아야 합니다.
--        받을 수 없는 숫자를 적어 두면 그게 곧 과장입니다.
-- ---------------------------------------------------------------------------
SELECT code AS 규칙, max_amount AS "표시 최대",
       (SELECT max((value)::int) FROM jsonb_each_text(r.payout)) AS "실제 최대",
       disclosure AS 고지
  FROM public.reward_rules r
 WHERE payout IS NOT NULL
 ORDER BY code;
