-- ===========================================================================
-- MEBODY — 보너스 주사위 고지에서 빠진 두 가지를 되살린다
--
-- ※ db/journey 폴더의 063 입니다.
--
-- 057·058 에서 금액을 고치며 고지 문구를 새로 썼는데, 원래 있던 두 문장을 빠뜨렸습니다.
--
--   · **선택**이라는 점 — 보상형 광고는 보고 싶은 사람만 봅니다. 강제가 아닙니다.
--   · **안 봐도 기본 적립은 그대로**라는 점 — 광고를 봐야 적립을 받는 구조로 오해하면 안 됩니다.
--
-- 이 둘은 문구 취향이 아니라 보상형 광고의 전제입니다. 기존 검증(verify:routine-bonus)이
-- 정확히 그 두 문장을 검사하고 있었고, 제가 지우는 바람에 실패로 드러났습니다.
--
-- 금액과 규칙은 바꾸지 않습니다. 말만 되돌립니다.
-- ===========================================================================

UPDATE public.reward_rules SET
  disclosure = '선택 항목입니다. 보지 않아도 기본 적립은 그대로 받습니다. '
            || '주사위 눈은 1~6이 각각 1/6 확률로 고르게 나오고, 6눈일 때만 1원이 적립됩니다. '
            || '하루 1회이며 다음 굴리기는 오전 5시에 열립니다. 무료 적립은 한 달 49원을 넘지 않습니다.',
  updated_at = now()
WHERE code = 'routine_bonus_dice';

-- ---------------------------------------------------------------------------
-- 확인 — 네 가지가 모두 들어 있어야 합니다.
-- ---------------------------------------------------------------------------
SELECT code AS 규칙,
       disclosure LIKE '%선택%'        AS "선택임을 밝힘",
       disclosure LIKE '%보지 않아도%' AS "안 봐도 기본 적립",
       disclosure LIKE '%1/6%'         AS "확률",
       disclosure LIKE '%한 달%'       AS "월 상한",
       max_amount AS "표시 최대",
       (SELECT max((value)::int) FROM jsonb_each_text(r.payout)) AS "실제 최대"
  FROM public.reward_rules r WHERE code = 'routine_bonus_dice';
